/* Pre-renders a font for the kernel's boot screen (kernel/drivers/bootscreen.c), which has no font renderer of
 * its own: the printable ASCII characters of one TrueType face at one pixel size, as 8-bit coverage, written as
 * a C header. Run on the build machine (tools/bakefont/bake.sh), its output committed.
 *
 *   bakefont FONT.ttf PIXELS NAME > header.h */
#define STB_TRUETYPE_IMPLEMENTATION
#include "stb_truetype.h"

#include <stdio.h>
#include <stdlib.h>

int main(int argc, char **argv) {
    if (argc != 4) {
        fprintf(stderr, "usage: bakefont FONT.ttf PIXELS NAME\n");
        return 2;
    }
    FILE *f = fopen(argv[1], "rb");
    if (!f) {
        perror(argv[1]);
        return 1;
    }
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    unsigned char *ttf = malloc((size_t)n);
    if (fread(ttf, 1, (size_t)n, f) != (size_t)n)
        return 1;
    fclose(f);
    stbtt_fontinfo info;
    if (!stbtt_InitFont(&info, ttf, stbtt_GetFontOffsetForIndex(ttf, 0)))
        return 1;
    float px = (float)atof(argv[2]);
    float scale = stbtt_ScaleForPixelHeight(&info, px);
    int ascent, descent, gap;
    stbtt_GetFontVMetrics(&info, &ascent, &descent, &gap);
    const char *name = argv[3];

    printf("/* %s at %s px, characters 32-126: generated by tools/bakefont from %s (SIL Open Font License). */\n",
           name, argv[2], argv[1]);
    printf("static const unsigned char %s_bits[] = {\n", name);
    int offs[95], ws[95], hs[95], xo[95], yo[95], adv[95], total = 0;
    for (int c = 32; c < 127; c++) {
        int i = c - 32, w = 0, h = 0, x0 = 0, y0 = 0, a, lsb;
        unsigned char *bm = stbtt_GetCodepointBitmap(&info, 0, scale, c, &w, &h, &x0, &y0);
        stbtt_GetCodepointHMetrics(&info, c, &a, &lsb);
        offs[i] = total, ws[i] = w, hs[i] = h, xo[i] = x0, yo[i] = y0;
        adv[i] = (int)(a * scale * 64.0f + 0.5f); /* in 1/64 px */
        for (int k = 0; k < w * h; k++)
            printf("%d,%s", bm[k], (total + k) % 24 == 23 ? "\n" : "");
        total += w * h;
        stbtt_FreeBitmap(bm, NULL);
    }
    printf("0};\n");
    printf("static const struct bootglyph %s_glyphs[95] = {\n", name);
    for (int i = 0; i < 95; i++)
        printf("    {%d, %d, %d, %d, %d, %d},\n", offs[i], ws[i], hs[i], xo[i], yo[i], adv[i]);
    printf("};\n");
    printf("static const struct bootfont %s = {%s_bits, %s_glyphs, %d, %d};\n", name, name, name,
           (int)(ascent * scale + 0.5f), (int)((ascent - descent + gap) * scale + 0.5f));
    return 0;
}
