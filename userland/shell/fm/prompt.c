#include "fm.h"

/* What the AI is told about Facet markup. Kept in one place so the
 * reference, the examples and the engine stay in step. */

const char *fm_reference(void) {
    return
        "FACET MARKUP: you write the whole desktop as one document. XML-like markup for structure, a CSS-like "
        "<style> for looks. It is not HTML: only the elements and properties below exist. Keep it under about "
        "200 lines, with no comments, so it arrives whole.\n"
        "\n"
        "DOCUMENT\n"
        "<facet>\n"
        "  <meta ai-name=\"..\" user-name=\"..\" rationale=\"why it looks like this, to them\"/>\n"
        "  APPS KEEP THEIR NAMES: every app is shown by its real name (Files, Notes, Settings, Terminal, About, the "
        "apps they installed by theirs; the companion by its own name). Never rename an app or give it a themed name: "
        "this is a working computer, and things must be found by what they are. Words on the desktop say something "
        "true and useful in plain language, or nothing: no slogans, mottos or poetic lines. bind=\"greeting\" shows a "
        "greeting by the hour with their name, bind=\"tagline\" the date: the system writes both.\n"
        "  <wallpaper kind=\"aurora|nebula|liquid|flow|prism|gradient|waves|bokeh|dunes|sun|constellation|paper\" "
        "colors=\"#base #light1 #light2 #depth\" seed=\"7\" intensity=\"0.2-1\"/>  (the first five move slowly; a "
        "background on desktop is painted over it, so use translucent colours there to tint it)\n"
        "  <desktop> surfaces </desktop>\n"
        "  <template id=\"window\"> the frame around every app window, with <slot/> where the app goes </template>\n"
        "  <style> rules </style>\n"
        "</facet>\n"
        "Write the parts in exactly this order, <style> last: they watch the desktop being built as you write, the "
        "pieces first, then each rule giving them their look.\n"
        "\n"
        "SURFACES are the direct children of <desktop>. Put each one somewhere:\n"
        "  dock=\"top|bottom|left|right\" attaches it to a screen edge and keeps windows clear of it; add "
        "width=\"full\" (top/bottom) or height=\"full\" (left/right) to span the edge, align=\"start|center|end\" "
        "to slide it along the edge, reserve=\"false\" to let windows go under it.\n"
        "  place=\"center|top|bottom|left|right|top-left|top-right|bottom-left|bottom-right|fill\" puts it in the "
        "space left over (margins offset it). over=\"screen\" ignores docked surfaces.\n"
        "  layer=\"above|below\": above or below app windows. taskbar, dock, menubar and bar are above by default; "
        "everything else is below (like widgets on a wallpaper).\n"
        "\n"
        "ELEMENTS (any other tag name works too and acts as a row container, so name things meaningfully)\n"
        "  row, column, grid, stack (children on top of each other), orbit (children around a circle), panel, "
        "taskbar, dock, menubar, bar, group: containers.\n"
        "  button what=\"action\" icon=\"name\">Label</button>: clickable. Any element with what=\"..\" is clickable.\n"
        "  text / label / title: text content, or bind=\"user.name|ai.name|greeting|tagline|rationale\".\n"
        "  icon name=\"..\": an app id (files, companion, ...) or a symbol: close minimize maximize plus grid menu "
        "search dot ring star sparkle wifi bell home moon sun chevron-up chevron-down chevron-left chevron-right, or a "
        "kind of file drawn as a picture: folder document image audio video archive code executable.\n"
        "  clock format=\"HH:MM|time12|seconds|date|day|words|any %strftime\" face=\"ring\" (optional ring dial).\n"
        "  applist apps=\"all\" or \"files,notes,...\" labels=\"below|none|hover\": one item per app. Each item is "
        "<item class=\"app\" app=\"id\"> holding an <icon> and a <label> (or a hover <tip>). Style them with "
        "selectors like \"applist item\", \"item:hover\", \"item icon\", \"item label\".\n"
        "  windowlist: one item per open window (like a taskbar); the focused one matches item:open.\n"
        "  search placeholder=\"..\": type to open an app by name, or ask the companion anything.\n"
        "  ai: you, as they chose to see you (a gem, a light, the Earth, a face...), alive with what you are doing; "
        "clicking it opens your conversation. (Older designs call it orb: the same thing.)\n"
        "  view app=\"companion|files|notes|settings|about|terminal\": that app embedded right in the desktop.\n"
        "  spacer (pushes things apart), divider (a hairline).\n"
        "  image src=\"..\": a picture on this computer (PNG, JPEG, GIF, BMP or SVG; a full path, ~/ for their "
        "home, or a name in /usr/share/os/pictures), fit=\"contain|cover|fill\". Give it a width or a height and it "
        "keeps its shape; image-rendering: pixelated scales it by whole pixels (for pixel art).\n"
        "  svg: a drawing written right here, for logos and marks: <svg viewBox=\"0 0 64 64\" width=\"32\" "
        "height=\"32\"><path d=\"...\" fill=\"#fff\"/></svg> (paths, shapes, gradients, strokes; no text or "
        "scripts inside). Size it like an image.\n"
        "  pixels: pixel art, written as rows of letters, each letter a pixel of its palette colour and \".\" clear: "
        "<pixels palette=\"k #000000, r #f03c24, g #88c999, b #0a52a0, y #f5ef4a\" scale=\"2\">\n..kkkk..\n.krrkggk\n"
        "</pixels> (scale: how many screen pixels each one is). Always drawn by whole pixels, never blurred: for "
        "retro icons, logos, cursors, the flag on a Start button, anything that should look hand-placed.\n"
        "  model src=\"..\": a real 3D model, a .glb as Blender exports it (a full path, ~/ for their home, or a name "
        "in /usr/share/os/models: app-wheel.glb, casino.glb), drawn live with physically based light: metal "
        "reflects, glass shows what is behind it, things glow, cast shadows and sit in their own shade. Use it for "
        "anything that should look made rather than drawn: a dial, a wheel of apps, chips and cards, a crest, a "
        "lamp. Its parts are clickable: an object Blender calls \"app:files\" opens Files; one with an \"action\" "
        "custom property runs it (any action a button can do); <part node=\"Name\" action=\"open:notes\" "
        "title=\"Notes\" hover=\"lift|glow|both|none\"/> inside the model adds or changes that. Attributes: "
        "turn=\"none|drag|scroll\" (they turn it), spin=\"20\" (degrees a second, by itself), yaw=\"0\" "
        "pitch=\"8\" (the angle it is seen from), zoom=\"1\", animation=\"name\" with play=\"loop|once|hover|click|"
        "scroll|none\" (scroll steps it: a wheel turning slice by slice; step=\"seconds\" a notch), "
        "light=\"top-left warm|cool|bright|dim\", studio=\"bright|night\", quality=\"high|fast\", "
        "camera=\"model|orbit\" (a model with its own camera is seen through it unless it turns). Size it with "
        "CSS like an image; it is square unless sized. You can make models yourself: see MAKING 3D in what your "
        "body can do.\n"
        "  canvas: for anything the elements can't express, write a small Lua script as its content defining "
        "draw(w, h, t) (t = seconds, for animation) and optionally click(x, y) returning an action string. Paint "
        "with g.rect(x,y,w,h,colour[,radius]), g.gradient(x,y,w,h,top,bottom[,radius]), g.circle(x,y,r,colour), "
        "g.glow(x,y,r,colour) (soft light), g.line(x0,y0,x1,y1,colour[,width]), g.arc(cx,cy,r,a0,a1,colour[,width]) "
        "(radians), g.text(x,y,str,colour[,size[,font]]), g.poly({x0,y0,x1,y1,...},colour) (a filled shape: "
        "project 3D points yourself and paint faces back to front for solid 3D scenes). It can read this "
        "computer: g.apps() gives {{id=,name=},...}; g.files(path) (\"~\" is home) gives {{name=,path=,dir=,"
        "size=},...}, folders first; g.pointer() gives x, y and whether the pointer is over it (for hover). g.clock() gives the local hour as a fraction (14.5 is half past two), then the weekday, day and month. "
        "click may return \"open:<app id>\" or \"file:<path>\" (a folder opens in Files). A canvas can be a "
        "whole desktop (place=\"fill\"): a 3D file system to fly over, a solar system of apps, an animated "
        "scene. Colours are \"#rrggbb\", \"rgba(..)\" or a variable name like \"--accent\". math, string and "
        "table are available; nothing else. Keep it light: it runs every frame with a strict time budget. Size it "
        "with CSS (size, width, height).\n"
        "  popover id=\"..\": a menu or panel that opens over everything next to the button that opens it "
        "(what=\"toggle:#id\"). placement=\"auto|above|below|left|right|center\", align=\"start|center|end\", "
        "anchor=\"#other\". It closes when they click elsewhere, press Esc, or pick something in it.\n"
        "  sheet id=\"..\": like a popover but covers the whole screen (launchers, overviews).\n"
        "  hotkey=\"meta\" on a button or popover: the Windows/Command key presses or opens it.\n"
        "\n"
        "ACTIONS (what=\"...\", several separated by ';')\n"
        "  open:<app id>   toggle:#id  show:#id  hide:#id  focus:#id   close-popovers   redesign\n"
        "  power:off  power:restart   window:close  window:minimize  window:maximize (inside the window template)\n"
        "  drag=\"window\" on an element in the template lets them move the window by it.\n"
        "\n"
        "WINDOW TEMPLATE: the root element is the frame (it matches :focus when that window is focused). Inside: "
        "a title area with drag=\"window\" and <text bind=\"window.title\"/>, buttons with window actions, and "
        "exactly one <slot/> that grows to hold the app. The frame carries app=\"files|terminal|...\" and title=: "
        "frame[app=\"terminal\"] { } styles one app's windows; <template id=\"window\" for=\"terminal notes\"> gives "
        "those apps a frame of their own.\n"
        "\n"
        "STYLE: CSS syntax. Selectors: tag, .class, #id, [attr], [attr=value] (also ^= $= *= ~=), descendant (a b), "
        "child (a > b), next sibling (a + b), later sibling (a ~ b), states :hover :active :open (an open popover, "
        "or the button whose popover is open) :focus, structure :first-child :last-child :only-child :empty "
        ":nth-child(2n+1|odd|even|3) :nth-last-child(), :not(x) for a simple x, and ::before / ::after with "
        "content: \"text\" (or attr(name)), styled like any box. A selector this doesn't know is refused, never "
        "half-matched. :root { --name: "
        "value } defines variables used as var(--name). Always define --bg --surface --text --muted --accent "
        "--accent2 --font-heading --font-body --radius in :root: the apps' own content uses them.\n"
        "Numbers are pixels. Properties:\n"
        "  layout: display (none|flex|grid|stack|orbit), direction (row|column), wrap, gap, align (start|center|"
        "end|stretch), align-self, justify (start|center|end|space-between|space-around|space-evenly), grow, "
        "orbit (radius), position: absolute with left/top/right/bottom, z-index, overflow (visible|hidden|scroll; "
        "scroll shows a scrollbar: scrollbar-color: thumb track, scrollbar-width: thin|none|px)\n"
        "  grid: display: grid with grid-template-columns / -rows (px, %, fr, auto, minmax(120px, 1fr), repeat(3, "
        "1fr), repeat(auto-fill, minmax(100px, 1fr))), grid-template-areas: \"head head\" \"side main\", gap (or "
        "row-gap / column-gap); items: grid-column / grid-row (\"span 2\", \"1 / 3\", \"1 / -1\"), grid-area: "
        "name. (columns: 3 is a shorthand for three equal columns.)\n"
        "  anchors: anchor-name: --menu on one element; on another, position-anchor: --menu and either "
        "position-area: bottom center (top|center|bottom with left|center|right, or span-left etc.), or insets "
        "like top: anchor(bottom) + 6; left: anchor(left) (anchor(--other right) for a different anchor), "
        "width: anchor-size(width); position-try-fallbacks: flip-block, flip-inline turns it to the other side "
        "when it would leave the screen. It follows its anchor wherever that is laid out.\n"
        "  @media (min-width: 900px) / (max-width: ...) / (orientation: portrait) { ... } for other screen "
        "sizes.\n"
        "  size: width, height, size (both), min-width, max-width, min-height, max-height (px, % or full), "
        "padding, margin (1-4 values)\n"
        "  look: background: a colour, rgba(), gradients with any number of stops and positions "
        "(linear-gradient(135deg, #1d2671 0%, #c33764 50%, #f7b733 100%), radial-gradient(circle at 30% 30%, ...), "
        "conic-gradient(from 0deg, ...), repeating-linear-gradient(45deg, #222 0 10px, #fc0 10px 20px)), or a "
        "picture: url(~/Pictures/x.png) with background-size (cover|contain|px|%), background-position, "
        "background-repeat, and a gradient or colour listed with it (\"linear-gradient(...), url(x) center/cover\" "
        "puts the gradient over the picture); opacity, "
        "radius (1-4 values, 50% = pill/circle), border (\"1 #fff\", \"2px outset #c0c0c0\"), border-style "
        "(solid|dashed|dotted|double|inset|outset|ridge|groove: the last four are carved, lit from the top left), "
        "border-width and border-color (1-4 values), border-top/right/bottom/left (\"2px solid #000\") and "
        "their -width/-color, border-gradient, shadow / box-shadow (\"x y blur colour\"; a list may add inset "
        "edges with no blur, drawn inside the border, the first on top: \"inset -1px -1px #0a0a0a, inset 1px 1px "
        "#fff, inset -2px -2px #808080, inset 2px 2px #dfdfdf\" is a raised Windows-95 bevel, swap the colours for "
        "pressed), glow (\"size colour\": a neon halo), blur (frosted glass behind it, 0-40), saturate (vibrancy "
        "behind it, 1-2)\n"
        "  text: color, font (\"Family 16\", \"bold italic 15px Inter\", \"600 14px Sora\"), font-family, font-size, "
        "font-weight (normal|medium|semibold|bold|100-900; every family has real or made-up weights), font-style "
        "(normal|italic), text-align (also centres wrapped lines), line-height, letter-spacing (px or em), "
        "text-transform (uppercase|lowercase|capitalize|none), text-shadow (\"x y blur colour\"), text-overflow "
        "(ellipsis|clip), white-space: nowrap, line-clamp (most lines shown), font-smooth: none (letters drawn "
        "with every pixel on or off, like an old screen; the pixel faces Silkscreen, Press Start 2P, VT323, Pixelify "
        "Sans, Jersey 10 and Micro 5 are always drawn so: use them at whole multiples of their size, e.g. Silkscreen "
        "8/16, Press Start 2P 8/16, VT323 16/20/24, Pixelify Sans 13/16/20), writing-mode (horizontal-tb | "
        "vertical-rl: reads top to bottom | sideways-lr: reads bottom to top, like a spine), rotate (90, -90 or "
        "180: turns the text in it; transform: rotate() with quarter turns does the same)\n"
        "  icons: icon-size, icon-shape (none|circle|squircle|square: none is the object alone, the others put it "
        "on a tile), icon-style: color (default: modern full-colour pictures with depth), mono (the same pictures "
        "in the text colour; glyph is the same), classic (glossy, outlined, XP-era), line (thin single-stroke "
        "symbols), or the older filled|glow|duotone tiles (which need an icon-shape). Set icon-style on :root to "
        "style every icon, the Files window's too. Linux apps show their own icons.\n"
        "  motion: transition (ms; hover/open changes ease over this), transform: scale(1.2) translate(x, y) "
        "rotate(-8deg) skew(10deg) (the box drawn turned or slanted, laid out upright), scale, translate. "
        "animation: name 2s ease-in-out 0.3s infinite alternate (duration, timing linear|ease|ease-in|ease-out|"
        "ease-in-out|cubic-bezier(...)|steps(4), delay, count|infinite, direction, fill forwards) with "
        "@keyframes name { from { ... } 50% { ... } to { ... } }: colours, opacity, transforms, shadows, "
        "glow, sizes in px and gradient stops move smoothly; the rest switches halfway.\n"
        "  effects: filter: blur(4px) brightness(1.2) contrast(1.1) grayscale(1) sepia(.5) saturate(2) "
        "hue-rotate(90deg) invert(1) opacity(.5) drop-shadow(...) (the element itself; blur:/backdrop-filter "
        "blur what is behind it); mix-blend-mode (multiply|screen|overlay|darken|lighten|difference|exclusion|"
        "color-dodge|color-burn|hard-light|soft-light); clip-path: circle(40% at 50% 50%) | ellipse() | "
        "inset(10px round 8px) | polygon(50% 0, 100% 100%, 0 100%); mask-image: linear-gradient(90deg, #000, "
        "transparent) (how opaque the mask is, is how much shows); box-shadow takes a list: several outer "
        "shadows (blur 0 for hard retro offsets, a 4th number spreads them) and inset ones; text-shadow takes a "
        "list too (layered neon).\n"
        "  rich text: inside a text, words and <b> <strong> <i> <em> <u> <s> <mark> <code> <kbd> <small> <a "
        "what=\"...\"> <span class=...> <br/> flow as one paragraph, each styled on its own (a link clickable); "
        "text-decoration: underline | line-through.\n"
        "  pointer: cursor: default (an arrow) | pointer (a hand) | text | crosshair | move | wait | not-allowed "
        "| none | url(~/x.png) hx hy, on :root for the whole design or on any element; without it the system's "
        "own soft dot is used.\n"
        "  the cascade: later rules win over earlier ones of the same weight, and an #id over a class over a tag, "
        "as in CSS; \"value !important\" wins over all of them (the element's style=\"\" too); \"unset\" (or "
        "initial) drops what earlier rules said for that property.\n"
        "Anything not listed here does nothing; you are told when you use it.\n"
        "SIZES THAT FEEL RIGHT (at 100%; the person's text-size choice scales them): body text 13-16, small print "
        "11-12, headings 18-28; a menu bar or slim title bar 22-30 tall, a classic taskbar 28-40, a modern one "
        "40-56, a dock's icons 40-64; menu rows 28-36; buttons with words 24-36 tall with 8-16 padding at the "
        "sides; title-bar buttons can be as small as 12-16 (the system lets small things be clicked a little around "
        "them, up to 24x24, so retro sizes are fine); icons in lists 16-24, in launchers 48-72; gaps 4-8 inside a "
        "bar, 12-24 between groups; window frames 1-4 thick. Make a bar's height hold what is in it: its own "
        "padding plus its tallest child.\n"
        "Text colour is checked against what is behind it at draw time, but choose readable colours anyway; text "
        "that is hard to read where it sits is marked in the element list you are shown.\n";
}

