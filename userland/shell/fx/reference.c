/* What the companion is told about Facet 2 (docs/facet2.md), to write apps
 * for the person: the rules small models break most first, then the whole
 * language in brief, then one complete app to copy the shape of. */
#include "fx.h"

const char *fx_reference(void) {
    return
        "FACET 2: you write apps for them in Facet 2. One file is one app. Write the WHOLE file between "
        "[[app:Name]] and [[/app]] (Name: one word, it names the file). It is checked before it runs; if it has "
        "problems you are told each one with its fix, and you write the whole file again.\n"
        "RULES MOST OFTEN BROKEN:\n"
        "- `end` closes code (app, state, derived, fn, if, for, view, style, component); `</tag>` or `/>` closes "
        "markup; every markup tag starts with <. Markup only inside view ... end.\n"
        "- change a value with `set x = ...` (state) or `let x = ...` (a new local), only inside fn. `==` compares.\n"
        "- not JS: no &&, ||, !, ===, =>, .length, .push; use and, or, not, ==, len(x), list + [x].\n"
        "- on:click=\"name(args)\" always calls a fn of the app. Colours and fonts only as token(...).\n"
        "- every <each> has key={...}. Mixing and with or needs brackets.\n"
        "SECTIONS, in this order (all optional but view):\n"
        "app Name category notes   (its kind: notes todo writing files photos music video chat mail news weather "
        "browser maps game clock calculator utility developer finance health education creative other)\n"
        "  data notes = files(\"~/Notes\", \".txt\")   live, read-only; may use state names. Also: file(path) "
        "{name,path,text}, setting(\"person.name\"), apps() [{id,name}], clock(1000) {time,hour,minute,second,"
        "weekday}. files() records: name, path, size, modified, dir.\n"
        "  state\n    query = \"\"\n  end\n"
        "  derived\n    shown = filter(notes, n -> contains(lower(n.name), lower(query)))\n  end\n"
        "  fn pick(n)\n    set open = n\n  end\n"
        "  view\n    <column> ... </column>\n  end\n"
        "  style\n    #id { prop: value; }\n  end\n"
        "  component Row(item, selected) ... end   (same sections, no data; tells its parent with emit \"picked\" "
        "item; used as <Row item={n} selected={x} on:picked=\"pick(value)\"/>)\n"
        "end\n"
        "STATEMENTS (fn only): set, let, if c then ... elseif c then ... else ... end, for x in list do ... end, "
        "return x, emit \"event\" value, a call. Effects: fs.read(path) fs.write(path, text) fs.remove(path) "
        "fs.rename(a, b) fs.mkdir(path) app.open(\"notes\", path) app.notify(text) ask(\"Sure?\") -> true/false "
        "prompt(\"Name?\", \"\") -> text or none; after(\"save\", 1000, save) runs fn save once (again restarts "
        "it); every(\"tick\", 1000, tick); cancel(\"save\").\n"
        "PERMISSIONS: before an app runs, the system works out from its code what it can reach and asks the person: "
        "every folder or file its paths name (\"~/Notes\", \"~/Todo.txt\"; a path made while it runs is kept to "
        "those), every server written in its URLs (\"https://api.x.com/v1?q=\" + q names api.x.com; a server made "
        "while it runs, \"https://\" + host, needs the general internet, which is warned about for most kinds of "
        "app). Name exactly what it needs and no more; a notes app with the internet gets a warning. Never: files "
        "outside home, ~/.config ~/.local ~/.var ~/.ssh and other private places, settings other than person.name "
        "companion.name design.accent design.dark clock.24h units language. Anything not allowed fails without "
        "stopping the app (fs.read gives none, fs.write false, net.* {ok: false, error}): show that calmly. What "
        "it uses only in fns is optional: the person may refuse it, so the app must still work without it.\n"
        "NETWORK: data w = web(\"https://...\", 600000) gives the reply's "
        "JSON (records, lists) or none until it arrives, fetched again every 600000 ms. In fns: let r = "
        "net.get(url) / net.post(url, {a: 1}) (a record goes as JSON) gives {ok, status, data, text, error}. "
        "Sockets: set conn = net.connect(\"irc.libera.chat\", 6697, \"tls lines\", heard) (\"tcp\" or "
        "\"tls\", then \"lines\" or \"bytes\"); fn heard(c, kind, data): kind is open, line (data: the text, "
        "without \\r\\n), bytes (a list of 0..255), closed or error. net.send(conn, \"PRIVMSG #x :hi\\r\\n\") "
        "(or a list of bytes), net.close(conn). json(value) makes JSON text; parse(text) reads it.\n"
        "EXPRESSIONS: \"text {x}\", 12, true, none, [a, b], {name: \"x\"}, a.b, list[0], if c then a else b, "
        "x -> expr (only as an argument). Library: len lower upper trim split join text number pad round floor "
        "ceil min max slice first last sort filter map find contains starts ends date(ms, \"%H:%M\") base "
        "dirname json parse. map/filter/find also take (x, i) -> ...\n"
        "VIEW: row column grid stack panel scroll text button input field checkbox icon image spacer divider, "
        "widgets <ring value={v} max={m} label=\"water\"/> <progress value={v} max={m}/> <chart kind=\"bar\" "
        "data={list} labels={list}/> (or kind=\"line\") <avatar text={name}/> <badge>3</badge>. Text: "
        "<text>Hi {name}</text>. Attributes: \"literal\", 12, or {expr}. on:click on:input on:change "
        "on:key=\"f(value)\" (value: enter esc up down left right tab... or the character). bind=\"stateName\" "
        "on input/field/checkbox; placeholder=\"..\" autofocus disabled={x} multiline checked={x}. "
        "<each in={list} as=\"n\" key={n.path} at=\"i\"> ... </each>  <if test={x}> ... <else/> ... </if>. "
        "class=\"a b\" and class:active={x}.\n"
        "LOOKS: never invent colours. Use the built-in classes, made from their design: surfaces card tile glass "
        "hero (accent gradient banner) sunken outline raised; emphasis primary soft quiet danger success glow; "
        "shape pill circle; type title heading label subtle big mono; layout spread center left stack wrap fill "
        "grid2 grid3 grid4 tight airy; motion lift. Style properties (pick only what classes can't do): "
        "background color border radius padding margin gap width height grow font size weight shadow blur "
        "opacity align justify direction transition gradient glow depth scale move text upper line columns "
        "outline; values token(accent) token(accent2) token(surface) token(text) token(muted) token(danger) "
        "token(success) token(font-heading)... Make apps beautiful: a hero at the top, cards in a grid, rings or "
        "charts for numbers, primary for the main action, pills for choices.\n"
        "EXAMPLE:\n"
        "[[app:Water]]\n"
        "app Water category health\n"
        "  data saved = file(\"~/.water\")\n"
        "  state\n    goal = 8\n  end\n"
        "  derived\n    glasses = if trim(saved.text) == \"\" then 0 else number(trim(saved.text))\n  end\n"
        "  fn sip(n)\n    fs.write(\"~/.water\", text(max(0, glasses + n)))\n  end\n"
        "  view\n"
        "    <column class=\"airy\">\n"
        "      <row class=\"hero spread\">\n"
        "        <column class=\"tight\">\n"
        "          <text class=\"label\">today</text>\n"
        "          <text class=\"title\">{glasses} of {goal} glasses</text>\n"
        "        </column>\n"
        "        <ring value={glasses} max={goal} label=\"water\"/>\n"
        "      </row>\n"
        "      <row class=\"center\">\n"
        "        <button class=\"soft pill\" on:click=\"sip(-1)\">One less</button>\n"
        "        <button class=\"primary pill\" on:click=\"sip(1)\">A glass</button>\n"
        "      </row>\n"
        "    </column>\n"
        "  end\n"
        "end\n"
        "[[/app]]\n";
}
