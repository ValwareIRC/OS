#!/usr/bin/env python3
"""Generates C tables for the OS's Wayland server from protocol XML.

  wlgen.py OUT.h protocol.xml [protocol.xml ...]

For every interface: its name and version, and for every request and event
its opcode (as a constant), its wire signature and, for new_id arguments,
the interface the new object has. The server demarshals requests and
marshals events from these tables, like libwayland does, so no per-message
code has to be written by hand.
"""
import sys
import xml.etree.ElementTree as ET

CODES = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o", "new_id": "n", "array": "a", "fd": "h"}


def sig(msg):
    s = ""
    since = msg.get("since")
    types = []
    for a in msg.findall("arg"):
        t = a.get("type")
        if a.get("allow-null") == "true":
            s += "?"
        if t == "new_id" and not a.get("interface"):
            s += "sun"  # wl_registry.bind: interface name, version, id
            types += [None, None, None]
            continue
        s += CODES[t]
        types.append(a.get("interface") if t in ("new_id", "object") else None)
    return (since or "1"), s, types


def cname(s):
    return s.upper()


def main():
    out = open(sys.argv[1], "w")
    out.write("/* Generated by userland/tools/wlgen.py from the Wayland protocol XML. Do not edit. */\n")
    out.write("#pragma once\n#include \"wlproto_types.h\"\n\n")
    ifaces = []
    for path in sys.argv[2:]:
        for itf in ET.parse(path).getroot().findall("interface"):
            ifaces.append(itf)
    names = [i.get("name") for i in ifaces]
    for itf in ifaces:
        out.write(f"extern const struct wl_iface {itf.get('name')}_iface;\n")
    out.write("\n")
    for itf in ifaces:
        n = itf.get("name")
        for kind in ("request", "event"):
            for op, m in enumerate(itf.findall(kind)):
                tag = "" if kind == "request" else "EV_"
                out.write(f"#define {cname(n)}_{tag}{cname(m.get('name'))} {op}\n")
        for e in itf.findall("enum"):
            for v in e.findall("entry"):
                out.write(f"#define {cname(n)}_{cname(e.get('name'))}_{cname(v.get('name'))} {v.get('value')}\n")
        out.write("\n")
    out.write("#ifdef WLPROTO_TABLES\n")
    for itf in ifaces:
        n = itf.get("name")
        for kind in ("request", "event"):
            msgs = itf.findall(kind)
            for op, m in enumerate(msgs):
                _, s, types = sig(m)
                if any(types):
                    arr = ", ".join(f"&{t}_iface" if t in names else "0" for t in types)
                    out.write(f"static const struct wl_iface *{n}_{kind}_{op}_types[] = {{{arr}}};\n")
            out.write(f"static const struct wl_msg {n}_{kind}s[] = {{\n")
            for op, m in enumerate(msgs):
                since, s, types = sig(m)
                t = f"{n}_{kind}_{op}_types" if any(types) else "0"
                out.write(f"    {{\"{m.get('name')}\", \"{s}\", {t}, {since}}},\n")
            if not msgs:
                out.write("    {0, 0, 0, 0},\n")
            out.write("};\n")
        nreq, nev = len(itf.findall("request")), len(itf.findall("event"))
        out.write(f"const struct wl_iface {n}_iface = {{\"{n}\", {itf.get('version')}, {nreq}, {n}_requests, "
                  f"{nev}, {n}_events}};\n\n")
    out.write("#endif\n")


main()
